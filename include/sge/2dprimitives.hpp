#ifndef SGE_INCLUDE_SGE_2DPRIMITIVES_HPP_
#define SGE_INCLUDE_SGE_2DPRIMITIVES_HPP_

#include <../src/math/Linear.hpp>

#include <utility>

namespace sge::geometry::objects2D
{

    /// Информация о количестве простейших элементов в объекте
    enum class ItemType
    {
        VERTEX = 3,  ///< Количество элементов в вершине (x, y, z)
        RGBA = 4,    ///< Количество элементов в цвете формата RGBA
        RGB = 3      ///< Количество элементов в цвете формата RGB
    };



    /**
     * @brief Простейший элемент геометрии
     * 
     * Не предназначен для рендеринга в качестве полноценного объекта
     */
    struct Vertex
    {
        /**
         * @brief Координата X
         * 
         * Положение вершины по горизонтали.\n
         * Ось X направлена вправо (растёт к правой стороне окна).
         */
        float x;
        /**
         * @brief Координата Y
         * 
         * Положение вершины по вертикали.\n
         * Ось Y направлена вниз (растёт к низу окна).
         */
        float y;
        /**
         * @brief Координата Z
         * 
         * Отвечает за глубину расположения вершины.\n
         * Ось Z направлена от глаз пользователя (растёт в глубину экрана). Объекты с меньшим значением Z отображаются поверх объектов с большим значением.
         */
        float z;

        /**
         * @brief Сдвигает вершину на указанное смещение
         * 
         * Функция изменяет координаты вершины, добавляя к текущим координатам указанные значения смещения по осям X, Y, Z.
         * @param[in] delta_pos Смещение по осям X, Y, Z
         * @return math::vec3 Итоговое положение вершины по осямX, Y, Z
         */
        math::vec3 move(math::vec3 delta_pos);
    };



    /**
     * @brief Простейший элемент геометрии с данными о цвете
     * 
     * Не предназначен для рендеринга в качестве полноценного объекта
     */
    struct VertexColorable
    {
        /**
         * @brief Координата X
         * 
         * Положение вершины по горизонтали.\n
         * Ось X направлена вправо (растёт к правой стороне окна).
         */
        float x;
        /**
         * @brief Координата Y
         * 
         * Положение вершины по вертикали.\n
         * Ось Y направлена вниз (растёт к низу окна).
         */
        float y;
        /**
         * @brief Координата Z
         * 
         * Отвечает за глубину расположения вершины.\n
         * Ось Z направлена от глаз пользователя (растёт в глубину экрана). Объекты с меньшим значением Z отображаются поверх объектов с большим значением.
         */
        float z;

        /**
         * @brief Цвет элемента
         * 
         * Цвет элемента в формате RGBA
         */
        math::vec4 color{.0f, .0f, .0f, .0f};

        /**
         * @brief Сдвигает точку на указанное смещение
         * 
         * Функция изменяет координаты точки, добавляя к текущим координатам указанные значения смещения по осям X, Y, Z.
         * @param[in] delta_pos Смещение по осям X, Y, Z
         * @return math::vec3 Итоговое положение вершины по осям X, Y, Z
         */
        math::vec3 move(math::vec3 delta_pos);
    };


    
    /**
     * @brief Геометрический примитив
     * 
     * Предназначен для рендеринга. Представляет из себя точку в виде квадрата.
     * @li Пример точки с координатами 50px по оси X, 20px по оси Y, с глубиной 0.2, ярко красного цвета, непрозрачная с толщиной 2 пикселя:
     * @code {C++}
     * sge::geometry::objects2D::Point point{{50.0f, 20.0f, 0.2f, {1.0f, 0.0f, 0.0f, 1.0f}}, 2};
     * @endcode
     * 
     */
    struct Point
    {
        /**
         * @brief Структура, содержащая в себе данные о положении и цвете
         * 
         * Цвет точки задается динамически. при изменении соответствующего поля структуры цвет точки так же изменится.
         * @see VertexColorable::x VertexColorable::y VertexColorable::z Для подробного описания системы координат.\n
         */
        VertexColorable vertex;

        /**
         * @brief Толщина точки
         * 
         * Толщина точки в пикселях. Например если задано значение 2, точка будет шириной и высотой 2 пикселя.
         */
        unsigned size = 1;
    };



    /**
     * @brief Геометрический примитив
     * 
     * Предназначен для рендеринга. Представляет из себя прямую линию.
     * @li Пример линии с координатами первой вершины ( @ref Line::start) 80.5px по оси X, 60px по оси Y, глубиной 0.1. Вторая вершина ( @ref Line::end) с координатами 160px по оси X, 120px по оси Y и глубиной 0.2. Толщина линии 5 пикселей. Градиент от голубого (первая вершина) до пурпурного (вторая вершина). Динамический цвет белый, то есть основной цвет остается без изменений.
     * @code {C++}
     * sge::geometry::objects2D::Line line {80.5f, 60.0f, 0.1f, {0.0f, 1.0f, 1.0f, 1.0f},},     // start голубой
                                           {160.1f, 120.0f, 0.2f, {1.0f, 0.0f, 1.0f, 1.0f}},    // end пурпурный
                                           {1.0f, 1.0f, 1.0f, 1.0f}, 5.0f};                     // color белый, толщина 5px
     * @endcode
     * 
     * @li Цвета:\n
     * Цвета вершин @ref Line::start и @ref Line::end статические. Они задаются при создании геометрии и после добавления на сцену ( @ref sge::Scene) не могут быть изменены. Разные цвета для двух точек образуют градиет.\n
     * Общий динамический цвет @ref Line::color может меняться после добавления на сцену. Он применяется ко всему объекту путём умножения на цвет каждой вершины. Например линия с цветами первой вершины {1.0f, 0.0f, 1.0fб 1.0f}, второй {0.0f, 1.0f, 0.0f, 1.0f} и общим цветом {0.0f, 1.0f, 0.5f, 1.0f} создаст градиет от синего до ярко зелёного цвета.
     */
    struct Line
    {

        /**
         * @brief Структура, содержащая в себе данные о положении первой вершины и статическом цвете
         * 
         * Цвет вершины задается статически. при изменении соответствующего поля после добавления на сцену ( @ref sge::Scene) цвет вершины не изменится.
         * @see VertexColorable::x VertexColorable::y VertexColorable::z Для подробного описания системы координат.\n
         */
        VertexColorable start;

        /**
         * @brief Структура, содержащая в себе данные о положении второй вершины и статическом цвете
         * 
         * Цвет вершины задается статически. при изменении соответствующего поля после добавления на сцену ( @ref sge::Scene) цвет вершины не изменится.
         * @see VertexColorable::x VertexColorable::y VertexColorable::z Для подробного описания системы координат.\n
         */
        VertexColorable end;

        /**
         * @brief Общий динамически изменяемый цвет линии
         * 
         * Цвет всей линии в формате RGBA. Модифицирует цвета вершин путём покомпонентного умножения:\n
         * @li final_color = vertex_color * this_color
         * @li По умолчанию {1,1,1,1} - не изменяет цвета вершин
         * @li Можно использовать для затемнения/осветления всей линии или как самостоятельный цвет линии, если цвета всех вершин равны {1,1,1,1} 
         */
        math::vec4 color{1.0f, 1.0f, 1.0f, 1.0f};

        /**
         * @brief Толщина линии
         * 
         * Толщина линии в пикселях. Например если задано значение 2, линия будет шириной 2 пикселя.
         */
        float thickness = 1.0f;

         /**
         * @brief Сдвигает всю линию на указанное смещение
         * 
         * Функция изменяет координаты линии, добавляя к текущим координатам всех вершин значения смещения по осям X, Y, Z.
         * @param[in] delta_pos Смещение по осям X, Y, Z
         * @return std::pair<math::vec3, math::vec3> Итоговое положение вершин по осям X, Y, Z
         */
        std::pair<math::vec3, math::vec3> move(math::vec3);
    };

}


#endif
